// Isolated workflow test, part 1: Get Started -> resume link -> application page.
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
const BASE = "http://127.0.0.1:3200", OUT = process.env.MOCK_OUTBOX, DB = process.env.DB_URL;
const sql = (q) => execFileSync("psql", [DB, "-XqAt", "-c", q]).toString().trim();
const outbox = () => readFileSync(OUT, "utf8").trim().split("\n").filter(Boolean).map((l) => JSON.parse(l));
const ok = (name, cond, detail = "") => console.log(`${cond ? "PASS" : "FAIL"} ${name}${detail ? " — " + detail : ""}`);
const browser = await chromium.launch();
const ctx = await browser.newContext();
const page = await ctx.newPage();
const usersBefore = sql("select count(*) from auth.users");
await page.goto(BASE + "/get-started/company");
await page.fill('input[name="full_name"]', "Isolated Applicant");
await page.fill('input[name="email"]', "applicant@example.invalid");
if (await page.$('input[name="company_name"]')) await page.fill('input[name="company_name"]', "Isolated Test Co");
if (await page.$('input[name="website"]')) await page.fill('input[name="website"]', "https://example.invalid");
await page.click('form button[type="submit"]');
await page.waitForTimeout(2500);
const body = await page.textContent("body");
ok("Get Started (company) accepted", /received|submitted|check your email|thank/i.test(body), body.match(/(Application[^.]*\.|Check[^.]*\.)/)?.[0] ?? "");
const reqRow = sql("select r.status||'|'||c.kind||'|'||coalesce(c.profile_id::text,'NULL')||'|'||c.status from public.access_requests r join public.verification_cases c on c.access_request_id=r.id where r.email='applicant@example.invalid'");
ok("application + case stored, no profile", /\|company_kyb\|NULL\|/.test(reqRow), reqRow);
ok("no auth user created by applying", sql("select count(*) from auth.users") === usersBefore, `users ${usersBefore} -> ${sql("select count(*) from auth.users")}`);
const mail = outbox().filter((m) => m.host === "api.resend.com");
const link = JSON.stringify(mail.at(-1)?.body ?? {}).match(/https?:\/\/[^"\\\s<>]+\/apply\/continue\?token=[A-Za-z0-9_-]+/)?.[0];
ok("resume email captured by mock (not sent)", mail.length >= 1 && !!link, `${mail.length} mock email(s), to ${mail.at(-1)?.body?.to}`);
await page.goto(link);
await page.waitForLoadState("networkidle");
ok("resume link opens the application", page.url().includes("/apply"), page.url());
writeFileSync(process.env.STATE, JSON.stringify({ link }));
await ctx.storageState({ path: process.env.STATE + ".ctx" });
console.log("BUTTONS:", (await page.$$eval("button", (bs) => bs.map((b) => b.textContent.trim()).filter(Boolean))).join(" | "));
console.log("INPUTS:", (await page.$$eval("input,select,textarea", (xs) => xs.map((x) => x.name + ":" + x.type).filter((s) => !s.startsWith(":")))).join(" "));
await browser.close();
